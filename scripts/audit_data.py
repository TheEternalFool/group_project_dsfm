"""Run the data-quality audit on the raw SSA files.

Usage:
    python scripts/audit_data.py                      # print to the terminal
    python scripts/audit_data.py --out docs/data-audit.md

Only tables whose raw files are present are audited.
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

from names_project import audit, data

HEADER = """# Data-quality audit

Generated by `scripts/audit_data.py` on {today} from the raw SSA files in
`data/raw/`. Re-run the script after refreshing the data; do not edit by hand.
Counts are *published* births: names with fewer than {min_count} occurrences
in a year (or state-year) are suppressed by SSA and are not included.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, help="write the Markdown report to this file")
    args = parser.parse_args()

    sections = [HEADER.format(today=date.today().isoformat(), min_count=data.SSA_MIN_COUNT)]
    for kind, loader in (("national", data.load_national_raw), ("state", data.load_state_raw)):
        try:
            df = loader()
        except FileNotFoundError:
            sections.append(
                f"## {kind.capitalize()} table\n\nNot audited: raw files not found. "
                "Run `python scripts/download_data.py` (see README).\n"
            )
            continue
        sections.append(audit.audit_to_markdown(audit.audit_frame(df, kind), audit.threshold_by_year(df)))

    report = "\n".join(sections)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report, encoding="utf-8")
        print(f"[ok] wrote {args.out}")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
